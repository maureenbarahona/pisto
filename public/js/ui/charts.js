/**
 * Returns an inline SVG string for the requested icon.
 * @param {string} name
 * @param {number} [size=20]
 * @returns {string}
 */
export function renderIcon(name, size = 20) {
  const pathMarkup = ICON_PATHS[name] || ICON_PATHS.wallet;
  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${pathMarkup}</svg>`;
}

/**
 * Generates the signature Pisto SVG Donut Ring Chart with interactive category segments.
 * @param {object} analytics
 * @returns {string} HTML/SVG markup
 */
export function renderPistoDonutChart(analytics) {
  const radius = 88;
  const circumference = 2 * Math.PI * radius;
  const activeCategories = (analytics.expenseCategories || []).filter((c) => c.amount > 0);
  const totalExpense = analytics.totalExpense || 0;
  const totalIncome = analytics.totalIncome || 0;
  const baseCurrency = analytics.baseCurrency || 'USD';

  let cumulativeFraction = 0;
  const segmentsSvg = activeCategories
    .map((cat) => {
      const fraction = totalExpense > 0 ? cat.amount / totalExpense : 0;
      const segmentLength = Math.max(2, fraction * circumference);
      const dashArray = `${segmentLength} ${circumference}`;
      const dashOffset = -(cumulativeFraction * circumference);
      cumulativeFraction += fraction;

      return `
        <circle
          class="donut-segment"
          cx="110"
          cy="110"
          r="${radius}"
          fill="transparent"
          stroke="${cat.color}"
          stroke-width="20"
          stroke-dasharray="${dashArray}"
          stroke-dashoffset="${dashOffset}"
          data-action="open-category-keypad"
          data-category-id="${cat.id}"
        >
          <title>${cat.name}: ${Money.format(cat.amount, baseCurrency)} (${cat.sharePct}%)</title>
        </circle>
      `;
    })
    .join('');

  return `
    <div class="donut-container">
      <svg class="donut-svg" viewBox="0 0 220 220" role="img" aria-label="Distribución de gastos por categoría">
        <!-- Base Track Ring -->
        <circle
          cx="110"
          cy="110"
          r="${radius}"
          fill="transparent"
          stroke="var(--surface-border)"
          stroke-width="20"
        />
        <g transform="rotate(-90 110 110)">
          ${segmentsSvg}
        </g>
      </svg>
      <div class="donut-center">
        <span class="donut-label">Gastos</span>
        <strong class="donut-expense-value" id="donut-total-expense">
          ${Money.format(totalExpense, baseCurrency)}
        </strong>
        <span class="donut-income-pill" id="donut-total-income" title="Ingresos del período">
          + ${Money.format(totalIncome, baseCurrency)}
        </span>
        <button
          type="button"
          class="btn-donut-quick-add"
          id="btn-donut-add-tx"
          data-action="open-keypad"
          aria-label="Registrar nueva transacción"
        >
          ${renderIcon('plus', 15)} Registrar
        </button>
      </div>
    </div>
  `;
}
